def slug(h):
    s = re.sub(r'[^\w\- ]', '', h.strip().lower().replace('`', ''))
    return s.replace(' ', '-')

def parse_tables(text):
    """{marker name: [rows (list of cell strings)]} for each table directly after a `<!-- check:NAME -->` line."""
    lines = text.split('\n'); out = {}; i = 0
    while i < len(lines):
        m = re.match(r'\s*<!--\s*check:(\w[\w-]*)\s*-->\s*$', lines[i])
        if m and not m.group(1) == 'example':
            j = i + 1
            while j < len(lines) and not lines[j].strip().startswith('|'): j += 1
            rows = []
            while j < len(lines) and lines[j].strip().startswith('|'):
                cells = [c.strip() for c in lines[j].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-{2,}:?', c) for c in cells): rows.append(cells)
                j += 1
            out[m.group(1)] = rows[1:]       # drop the header row
            i = j
        else: i += 1
    return out

def num(s):
    s = re.sub(r'[\s,*`_]', '', s)
    s = s.replace('x', '').replace('X', '').replace('+', '')
    return int(s)

