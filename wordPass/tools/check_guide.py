def rng(cell, top=20):
    """The inclusive range a first-column cell names: "3", "5 to 6", "9 and up", "17 and up"."""
    nums = [int(x) for x in re.findall(r'\d+', cell)]
    lo = nums[0]
    hi = top if 'up' in cell else (nums[1] if len(nums) > 1 else lo)
    return lo, hi

def kvs(m):
    return dict(p.split('=', 1) for p in m.group(1).split())

def main():
    if not os.path.exists(GUIDE): raise SystemExit('docs/GUIDE.md is missing')
    text = read(GUIDE)
    tables = parse_tables(text)

    examples = [kvs(m) for m in re.finditer(r'<!--\s*check:example\s+(.*?)-->', text)]
    bonuses = [kvs(m) for m in re.finditer(r'<!--\s*check:bonus\s+(.*?)-->', text)]
    queries = [('P', e['base'], e['len'], e.get('burn', 0), e.get('diamonds', 0), e.get('repeat', 0)) for e in examples]
    queries += [('B', b['shelf'], b['turn'], b['peels'], b['len']) for b in bonuses]
    F = build_facts(queries)
    D = game_h_defines()

    # ---- worked examples score what the game scores
    for e, got in zip(examples, F['points']):
        if int(e['expect']) != got: fail(f'example {e.get("name", "?")}: guide says {e["expect"]}, boardWordPoints gives {got}')
    if len(examples) < 3: fail('the guide needs at least three worked scoring examples (<!-- check:example ... -->)')
    for b, got in zip(bonuses, F['bonuses']):
        want = [int(b['reward']), int(b['shelfb']), int(b['speed']), int(b['peel']), int(b['kind'])]
        if want != got: fail(f'bonus example shelf {b["shelf"]} turn {b["turn"]}: guide {want}, game {got}')

    def need(name):
        if name not in tables: fail(f'missing table marker <!-- check:{name} -->'); return None
        return tables[name]

    # ---- scoring tables
    t = need('values')            # | Value | Letters |
    if t:
        got = {}
        for r in t:
            for L in r[1].split(): got['QU' if L.upper() == 'Q' else L.upper()] = num(r[0])
        for i, v in enumerate(F['values']):
            L = 'QU' if i == 16 else chr(65 + i)
            if got.get(L) != v: fail(f'letter value {L}: guide {got.get(L)}, game {v}')
    t = need('values-az')         # | Letter | Value |
    if t:
        got = {r[0].upper(): num(r[1]) for r in t}
        for i, v in enumerate(F['values']):
            L = 'QU' if i == 16 else chr(65 + i)
            if got.get(L) != v: fail(f'appendix letter value {L}: guide {got.get(L)}, game {v}')
        if len(t) != 26: fail('the appendix letter table has 26 rows (Qu for Q)')
    t = need('lenmult')           # | Letters | Multiplier |
    if t:
        covered = set()
        for r in t:
            lo, hi = rng(r[0])
            for n in range(lo, hi + 1):
                covered.add(n)
                if F['lenmult'][n - 1] != num(r[1]): fail(f'length multiplier at {n} letters: guide {r[1]}, game {F["lenmult"][n - 1]}')
        if not set(range(3, 21)) <= covered: fail('the multiplier table must cover 3 to 20 letters')
    t = need('heat')              # | Word length | Heat |
    if t:
        covered = set()
        for r in t:
            lo, hi = rng(r[0])
            for n in range(lo, hi + 1):
                covered.add(n)
                if F['heat'][n - 1] != num(r[1]): fail(f'heat for a {n}-letter word: guide {r[1]}, game {F["heat"][n - 1]}')
        if not set(range(3, 21)) <= covered: fail('the heat table must cover 3 to 20 letters')
    t = need('overtime')          # | Turns past the limit | Extra heat every turn |
    if t:
        for r in t:
            lo, hi = rng(r[0])
            for over in (lo, hi):
                for lock in (0, 1):
                    turn = F['overtime'][lock] + over
                    if turn > 130: continue
                    if F[f'overtime{lock}'][turn - 1] != num(r[1]): fail(f'overtime heat {over} turns past the limit (lockdown {lock}): guide {r[1]}, game {F[f"overtime{lock}"][turn - 1]}')
        if F['overtime'] != [D['OVERTIME_TURNS'], D['OVERTIME_TURNS_LOCKDOWN']]: fail('overtime limits differ from game.h')
        if F['pulse'] != 2: fail(f'the Lockdown pulse is {F["pulse"]}, the guide says 2')
        if F['peelheat'] != [1, 2]: fail(f'peel heat {F["peelheat"]}, the guide says 1 and 2')
    t = need('bonuses')           # | Bonus | Per shelf number |
    if t:
        b = F['bonus']
        want = {'pass letter': b['letter3'] // 3, 'shelf cleared': b['shelf3'] // 3, 'speed': (b['speed2_30'] // 2) // 10, 'perfect': b['perfect2'][0] // 2, 'clean': b['clean2'][0] // 2}
        seen = set()
        for r in t:
            for k, v in want.items():
                if r[0].lower().startswith(k):
                    seen.add(k)
                    if num(r[1]) != v: fail(f'bonus "{r[0]}": guide {r[1]}, game {v} per shelf')
        if seen != set(want): fail(f'bonus table is missing {set(want) - seen}')

    # ---- the ladder, fire settings, twists, Daily modifiers, neighbours
    L = {x['shelf']: x for x in F['ladder']}
    t = need('ladder')            # | Shelf | Meter | Fire every | Lockdown | Pulse | First pass row | Pass length |
    if t:
        for r in t:
            lo, hi = rng(r[0], 30)
            for shelf in range(lo, hi + 1):
                x = L[shelf]
                got = [r[1], r[2], r[3].lower(), r[4], r[5], r[6]]
                want = [str(x['rule_threshold']), str(x['rule_every']), 'yes' if x['lockdown'] else 'no', str(x['rule_pulse']) if x['lockdown'] else '-', str(x['minrow']), str(x['passlen'])]
                if got != want: fail(f'ladder shelf {shelf}: guide {got}, game {want}')
        if sorted({rng(r[0], 30)[0] for r in t}) != list(range(1, 17)) + [17]: fail('the ladder table must list shelves 1 to 16 and a row for 17 and up')
    t = need('fire-settings')     # | Shelf | RELAXED | NORMAL | FAST |   "meter / every"
    if t:
        for r in t:
            x = L[num(r[0])]
            if x['twistshelf']: fail(f'FIRE table lists twist shelf {x["shelf"]}'); continue
            for col, f in ((1, 'f0'), (2, 'f1'), (3, 'f2')):
                want = f'{x[f][0]} / {x[f][1]}'
                if r[col].replace(' ', '') != want.replace(' ', ''): fail(f'FIRE setting table shelf {x["shelf"]} col {col}: guide {r[col]}, game {want}')
    t = need('twists')            # | Shelf | INK SPILL | DAMP | BURIED |   "meter / every / pass length"
    if t:
        for r in t:
            x = L[num(r[0])]
            if not x['twistshelf']: fail(f'twist table lists shelf {x["shelf"]}, which has no twist'); continue
            for col, tw in ((1, 't1'), (2, 't2'), (3, 't3')):
                v = x.get(tw)
                want = f'{v[0]} / {v[1]} / {v[2]}' if v else '-'
                if r[col].replace(' ', '') != want.replace(' ', ''): fail(f'twist table shelf {x["shelf"]} col {col}: guide {r[col]}, game {want}')
        if [i for i in range(1, 31) if F['ladder'][i - 1]['twistshelf']][:5] != [4, 7, 10, 13, 16]: fail('twist shelves are not 4, 7, 10, 13, 16 ...')
    t = need('daily-mods')        # | Modifier | Meter | Fire every | First pass row | Pass length |
    if t:
        names = ['STANDARD', 'EMBER', 'DEEP', 'LONG']
        if [r[0].replace('*', '').strip().upper() for r in t] != names: fail('Daily modifier rows are STANDARD, EMBER, DEEP, LONG in that order')
        for i, r in enumerate(t):
            d = F['daily'][i]
            if num(r[1]) != d[0] or num(r[2]) != d[1] or num(r[3]) != d[3]: fail(f'Daily modifier {names[i]}: guide {r[1:4]}, game {d}')
            if names[i] == 'LONG' and str(D['DAILY_LONG_LEN']) not in r[4]: fail(f'Daily LONG pass length: guide {r[4]}, game {D["DAILY_LONG_LEN"]}')
    # the modifier hash: the Python reading of the formula in the guide must equal boardDailyMod
    for seed, mod in F['dailymod']:
        if (((seed * 2654435761) & 0xFFFFFFFF) >> 28) & 3 != mod: fail(f'daily modifier hash for {seed}: game {mod}')
    t = need('neighbours')        # | Column | Neighbours as (dx, dy) |
    if t:
        for r in t:
            par = 'odd' if 'odd' in r[0].lower() else 'even'
            pairs = sorted(tuple(int(v) for v in m) for m in re.findall(r'\(\s*([+-]?\d+)\s*,\s*([+-]?\d+)\s*\)', r[1]))
            if pairs != sorted(tuple(x) for x in F['neigh'][par]): fail(f'neighbour offsets for {par} columns: guide {pairs}, game {sorted(F["neigh"][par])}')

    # ---- constants table equals game.h
    t = need('constants')         # | Name | Value | Meaning |
    if t:
        for r in t:
            name = r[0].strip('`')
            if name not in D: fail(f'constants table: {name} is not a #define in game.h'); continue
            if num(r[1]) != D[name]: fail(f'constants table: {name} is {D[name]} in game.h, the guide says {r[1]}')
        listed = {r[0].strip('`') for r in t}
        for must in ('COLS', 'ROWS', 'MAX_CHAIN', 'MAX_WORD', 'SCORE_UNIT', 'LONG_WORD_BONUS', 'BOOKMARKS_MAX', 'OVERTIME_TURNS', 'LOCKDOWN_FROM_SHELF',
                     'SPEED_TURNS', 'PERFECT_PER_SHELF', 'CLEAN_PER_SHELF', 'INK_SPILL_HOLES', 'DIAMOND_CAP', 'BURN_BONUS_PER_LETTER', 'LEDGER_N'):
            if must not in listed: fail(f'constants table should list {must}')

    # ---- options table equals gfx.c
    N = gfx_names()
    t = need('options')           # | Option | Values | Effect |
    if t:
        rows = {r[0].upper(): [v.strip().upper() for v in r[1].split(',') if v.strip()] for r in t}
        if [r[0].upper() for r in t] != N['OPT_NAMES']: fail(f'options table rows {[r[0] for r in t]} != gfx.c {N["OPT_NAMES"]}')
        for name, key in (('THEME', 'THEME_NAMES'), ('FRAME', 'FRAME_NAMES'), ('ACCENT', 'ACCENT_NAMES'), ('FIRE', 'FIRE_NAMES'), ('LIBRARY', 'LIB_NAMES'), ('SPELLING', 'SPELL_NAMES')):
            if rows.get(name) != N[key]: fail(f'options: {name} values {rows.get(name)} != gfx.c {N[key]}')
        if rows.get('HAND') != ['RIGHT', 'LEFT'] or rows.get('MUSIC') != ['ON', 'OFF']: fail('options: HAND and MUSIC values')
    if 'LANGUAGE' in N['OPT_NAMES']: fail('the options now have a LANGUAGE row: update sections 11 and 14 of the guide (and regenerate the pictures with make guide)')

    # ---- themes table equals pools.bin
    P = pools()
    t = need('themes')            # | Shelf | Theme | Words | Examples |
    if t:
        if len(t) != len(P): fail(f'theme table has {len(t)} rows, pools.bin has {len(P)} themes')
        if F['themes'] != len(P): fail('poolThemeCount disagrees with pools.bin')
        for i, r in enumerate(t):
            if i >= len(P): break
            name, words = P[i]
            if num(r[0]) != i + 1: fail(f'theme row {i + 1} is numbered {r[0]}')
            if r[1].strip('*` ').upper() != name: fail(f'theme {i + 1}: guide {r[1]}, pools.bin {name}')
            total = sum(len(v) for v in words.values())
            if num(r[2]) != total: fail(f'theme {name}: guide says {r[2]} words, pools.bin has {total}')
            ex = [w.strip().lower() for w in r[3].split(',') if w.strip()]
            allw = {w.lower() for v in words.values() for w in v}
            if len(ex) < 5: fail(f'theme {name}: give at least five example words')
            for w in ex:
                if w not in allw: fail(f'theme {name}: example "{w}" is not in its pool')
        grand = sum(len(v) for _, w in P for v in w.values())
        m = re.search(r'holds \*\*([\d,]+) pass words\*\*', text)
        if not m or int(m.group(1).replace(',', '')) != grand: fail(f'the guide should say the library holds {grand:,} pass words')
    t = need('pool-lengths')      # | Theme | 4 | 5 | 6 | 7 | 8 | 9 |
    if t:
        byname = {n: w for n, w in P}
        for r in t:
            w = byname.get(r[0].strip('*` ').upper())
            if w is None: fail(f'pool-lengths: unknown theme {r[0]}'); continue
            for k, ln in enumerate(range(4, 10)):
                if num(r[1 + k]) != len(w[ln]): fail(f'pool-lengths {r[0]} length {ln}: guide {r[1 + k]}, pools.bin {len(w[ln])}')

    # ---- dictionary table, by length
    counts, rare = dict_counts()
    t = need('dict-counts')       # | Letters | Multiplier | Heat | Words | Rare tier |
    if t:
        if [num(r[0]) for r in t] != list(range(3, 21)): fail('the dictionary table must have rows for 3 to 20 letters')
        for r in t:
            ln = num(r[0])
            if ln < 3 or ln > 20: continue
            if num(r[1]) != F['lenmult'][ln - 1]: fail(f'appendix {ln} letters: multiplier guide {r[1]}, game {F["lenmult"][ln - 1]}')
            if num(r[2]) != F['heat'][ln - 1]: fail(f'appendix {ln} letters: heat guide {r[2]}, game {F["heat"][ln - 1]}')
            if num(r[3]) != counts[ln - 3]: fail(f'dictionary {ln} letters: guide {r[3]}, dict.bin {counts[ln - 3]}')
            if num(r[4]) != rare[ln - 3]: fail(f'dictionary {ln} letters: rare guide {r[4]}, dict.bin {rare[ln - 3]}')
    total = sum(counts)
    m = re.search(r'<!--\s*check:dict-total\s+(\d+)\s*-->', text)
    if not m or int(m.group(1)) != total: fail(f'dict-total marker: want {total}')
    for claim in (f'{total:,}', f'{sum(rare):,}', f'{total - sum(rare):,}'):
        if claim not in text: fail(f'the guide should quote the dictionary figure {claim}')
    pct = round(100 * (total - sum(rare)) / total)
    if f'about {pct} in 100 dictionary words' not in text: fail(f'LIBRARY COMMON accepts about {pct} in 100 words: fix the sentence in section 4.2')
    us, uk = variants_counts()
    m = re.search(r'<!--\s*check:variants\s+us=(\d+)\s+uk=(\d+)\s*-->', text)
    if not m or (int(m.group(1)), int(m.group(2))) != (us, uk): fail(f'variants marker: want us={us} uk={uk}')
    if f'{us:,} American-only and {uk:,} British-only' not in text: fail(f'the guide should say {us:,} American-only and {uk:,} British-only words')
    t = need('spelling-probes')   # | Word | BOTH | AMERICAN | BRITISH |
    if t:
        for r in t:
            w = r[0].strip('`*').lower(); tier, var = F['words'][w]
            exp = ['yes' if tier != 0 and not (s != 0 and var and var != s) else 'no' for s in (0, 1, 2)]
            got = [c.lower().split()[0] for c in r[1:4]]
            if got != exp: fail(f'spelling probe {w}: guide {got}, game {exp}')
    t = need('files')             # | File | Format | Size in bytes | What |
    if t:
        for r in t:
            name = r[0].strip('`')
            if name.startswith('data/'):
                size = os.path.getsize(os.path.join(REPO, name))
                if num(r[2]) != size: fail(f'{name} is {size:,} bytes, the guide says {r[2]}')
                with open(os.path.join(REPO, name), 'rb') as f:
                    if f.read(4).decode() != r[1]: fail(f'{name}: the magic is not {r[1]}')
            elif 'cfg' in name:
                if num(r[2]) != F['settings_size']: fail(f'wordPass.cfg is {F["settings_size"]} bytes (sizeof Settings), the guide says {r[2]}')
        if '136 bytes' not in text or F['settings_size'] != 136: fail('the guide says wordPass.cfg is 136 bytes; sizeof(Settings) disagrees')

    # ---- music: the numbers the guide quotes are the ones music.c has
    music = read(os.path.join(SRC, 'music.c'))
    t = need('music')             # | Constant | Value |
    if t:
        for r in t:
            m = re.search(r'#define\s+' + re.escape(r[0].strip('`')) + r'\s+(\d+)', music)
            if not m or int(m.group(1)) != num(r[1]): fail(f'music constant {r[0]}: music.c has {m.group(1) if m else "nothing"}, the guide says {r[1]}')
    t = need('music-keys')        # | Shelf | 1 | ... | 8 |  then | Key | ... |
    if t:
        m = re.search(r'static const u8 keys\[\]\s*=\s*\{([^}]*)\}', music)
        keys_ = [int(x) for x in m.group(1).split(',') if x.strip()] if m else []
        if [num(c) for c in t[0][1:]] != keys_: fail(f'music keys: music.c has {keys_}, the guide says {t[0][1:]}')

    # ---- controls: every key main.c reads is in the control table
    t = need('controls')          # | Input | Where | Action |
    mainc = read(os.path.join(SRC, 'main.c'))
    keys = sorted(set(re.findall(r'KEY_([A-Z]+)', mainc)) - {'TOUCH'})
    names = {'A': 'A', 'B': 'B', 'X': 'X', 'Y': 'Y', 'L': 'L', 'R': 'R', 'START': 'START', 'SELECT': 'SELECT', 'UP': 'D-PAD', 'DOWN': 'D-PAD', 'LEFT': 'LEFT', 'RIGHT': 'RIGHT'}
    if t:
        col0 = ' '.join(r[0].upper().replace('*', '') for r in t)
        for k in keys:
            if not re.search(r'(?<![A-Z-])' + re.escape(names.get(k, k)) + r'(?![A-Z])', col0): fail(f'control table does not mention {k} (main.c reads KEY_{k})')
        if 'STYLUS' not in col0: fail('control table does not mention the stylus')
        for r in t:
            if len(r) != 3: fail(f'control row {r[0]} does not have three columns')
    sec = section(text, 'Screens and controls')
    for k in keys:
        if not re.search(r'\b' + names.get(k, k).replace('-', r'[- ]') + r'\b', sec, re.I): fail(f'controls section never mentions {k}')
    # the other direction: every key the table names is really read
    for r in (t or []):
        for tok in re.findall(r'\b(START|SELECT|A|B|X|Y|L|R)\b', r[0].replace('*', '')):
            if tok not in keys: fail(f'control table names {tok}, which main.c never reads')

    # ---- messages and callouts quoted in the guide exist in the source
    allsrc = read(os.path.join(SRC, 'main.c')) + read(os.path.join(SRC, 'gfx.c')) + read(os.path.join(SRC, 'board.c'))
    for tname in ('messages', 'callouts'):
        t = need(tname)           # | Message | When |
        for r in (t or []):
            msg = r[0].strip('`*').strip()
            if '"' + msg + '"' not in allsrc: fail(f'{tname[:-1]} "{msg}" is not a string in the source')
    t = need('fail-cards')        # | Card | Cause |
    if t:
        names_ = [r[0].strip('`*').strip() for r in t]
        if names_ != F['failnames']: fail(f'fail cards {names_} != game {F["failnames"]}')

    # ---- images, captions, declarations
    check_images(text)
    check_links(text)
    check_scope(text)
    check_readme()

    if errors:
        print('GUIDE CHECK FAILED:'); [print('  -', e) for e in errors]
        return 1
    print(f'GUIDE OK: {len(tables)} tables, {len(examples)} worked examples, {len(bonuses)} bonus examples, {len(re.findall(r"!\[", text))} images checked against the repository')
    return 0

def section(text, title):
    m = re.search(r'^## .*' + re.escape(title) + r'.*$', text, re.M)
    if not m: fail(f'no section "{title}"'); return ''
    n = re.search(r'^## ', text[m.end():], re.M)
    return text[m.end(): m.end() + n.start()] if n else text[m.end():]

def declared_shots():
    src = read(os.path.join(HERE, 'emu', 'screens.py'))
    files = set()
    for m in re.finditer(r'^@shot\((.*?)\)\s*$', src, re.M):
        files.update(re.findall(r"'([^']+\.png)'", m.group(1)))
    return files

def check_images(text):
    decl = declared_shots(); used = set()
    for m in re.finditer(r'!\[([^\]]*)\]\(([^)]+)\)', text):
        alt, path = m.group(1), m.group(2)
        used.add(os.path.basename(path))
        if len(alt.strip()) < 12: fail(f'image {path}: alt text too short')
        if not os.path.exists(os.path.join(DOCS, path)): fail(f'image {path} does not exist')
        if os.path.basename(path) not in decl: fail(f'image {path} is not produced by tools/emu/screens.py (no @shot declares it)')
        after = text[m.end():].lstrip('\n')
        if not after.startswith('*'): fail(f'image {path}: no italic caption on the next line')
    img = os.path.join(DOCS, 'img')
    if os.path.isdir(img):
        for f in sorted(os.listdir(img)):
            if f.endswith('.png') and f not in used: fail(f'docs/img/{f} is not used by the guide')
    for f in sorted(decl):
        if f not in used: fail(f'screens.py declares {f} but the guide does not show it')

def check_links(text):
    heads = {slug(h) for h in re.findall(r'^#{1,4}\s+(.*)$', text, re.M)}
    for m in re.finditer(r'\]\(#([^)]+)\)', text):
        if m.group(1) not in heads: fail(f'in-page link #{m.group(1)} has no heading')
    for m in re.finditer(r'\]\((?!https?:|#)([^)]+)\)', text):
        p = m.group(1).split('#')[0]
        if p and not p.startswith('img/') and not os.path.exists(os.path.normpath(os.path.join(DOCS, p))): fail(f'link {p} does not exist')
    toc = re.search(r'^## .*[Cc]ontents.*?(?=^## )', text, re.S | re.M)
    if not toc: fail('no table of contents')
    else:
        linked = set(re.findall(r'\]\(#([^)]+)\)', toc.group(0)))
        for h in re.findall(r'^## (.*)$', text, re.M):
            if slug(h) not in linked and 'contents' not in h.lower(): fail(f'the table of contents does not link "{h}"')
    for sec_ in ('Music and sound', 'Languages'):
        s = section(text, sec_)
        if 'screens.py' not in s or 'check_guide.py' not in s: fail(f'section "{sec_}" must carry the note that the script regenerates it and check_guide.py checks it')

def check_scope(text):
    bad = re.findall(r'\b(claude|anthropic|chatgpt|gemini|(?:sonnet|opus|haiku)\s+\d)', text, re.I)
    if bad: fail(f'the guide names a model or vendor: {set(bad)}')
    if re.search(r'BOOKWORM X MINESWEEPER', text, re.I): fail('the removed tagline appears in the guide')

def check_readme():
    r = read(os.path.join(REPO, 'README.md'))
    if 'docs/GUIDE.md' not in r: fail('README.md does not link docs/GUIDE.md')
    for m in re.finditer(r'\]\((docs/[^)#]+)', r):
        if not os.path.exists(os.path.join(REPO, m.group(1))): fail(f'README links {m.group(1)}, which does not exist')

