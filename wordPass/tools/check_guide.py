#!/usr/bin/env python3
"""Check docs/GUIDE.md against the repository.

    python3 tools/check_guide.py            # exits 0 and prints GUIDE OK when every check passes

The guide is a manual, and a manual that drifts from the game is worse than none. This script
keeps it honest:

  * every image link points at a file in docs/img, has alt text and a caption, and every shot is
    declared in tools/emu/screens.py (so `make guide` can regenerate it);
  * every table marked `<!-- check:NAME -->` equals what the game computes. The numbers do not come
    from a copy of the rules: a small C program is compiled against source/board.c (the same way
    `make check` builds it) and asked, so the guide is compared with the code that runs;
  * the theme table equals data/pools.bin, the dictionary table equals data/dict.bin, the constants
    table equals game.h, the options table equals gfx.c, the control table mentions every key main.c reads;
  * the worked examples (`<!-- check:example ... -->`) score what boardWordPoints scores;
  * the table of contents and the in-page links all resolve.

Sections that depend on code still in flux (Music, Languages) are marked as regenerated by the
script, and their tables are checked here too, so a later pass finds out cheaply what moved.
"""
