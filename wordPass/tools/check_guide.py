def build_facts(queries=()):
    """Compile the facts program against the game's own board.c and run it. `queries` is a list of tuples:
    ('P', base, len, burn, diamonds, repeat) scored with boardWordPoints, ('B', shelf, turn, peels, passLen) with the bonus helpers."""
    out = tempfile.mkdtemp(prefix='guide_facts_')     # not build/: the ROM build leaves its own dict_bin.h there
    cfile = os.path.join(out, 'guide_facts.c'); exe = os.path.join(out, 'guide_facts')
    with open(cfile, 'w') as f: f.write(FACTS_C)
    cmd = ['gcc', '-std=gnu11', '-w', '-I', os.path.join(REPO, 'tools/check/stub'), '-I', SRC, cfile,
           os.path.join(REPO, 'tools/check/stubs.c'), os.path.join(SRC, 'board.c'), os.path.join(SRC, 'dict.c'),
           os.path.join(SRC, 'pools.c'), os.path.join(SRC, 'music.c'), '-o', exe]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: raise SystemExit('cannot build the facts program:\n' + r.stderr)
    qfile = os.path.join(out, 'queries.txt')
    with open(qfile, 'w') as f:
        for qq in queries: f.write(' '.join(str(x) for x in qq) + '\n')
    args = [exe, os.path.join(REPO, 'data/dict.bin'), os.path.join(REPO, 'data/pools.bin'), os.path.join(REPO, 'data/variants.bin'), qfile]
    r = subprocess.run(args, capture_output=True, text=True, cwd=REPO)
    if r.returncode: raise SystemExit('the facts program failed:\n' + r.stdout + r.stderr)
    shutil.rmtree(out, ignore_errors=True)
    return json.loads(r.stdout)

