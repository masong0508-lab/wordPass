def game_h_defines():
    d = {}
    for m in re.finditer(r'^#define\s+([A-Z_0-9]+)\s+(-?\d+)\b', read(os.path.join(SRC, 'game.h')), re.M):
        d[m.group(1)] = int(m.group(2))
    return d

def pools():
    """[(name, {len: [words]})] parsed from data/pools.bin (WPP1)."""
    p = open(os.path.join(REPO, 'data/pools.bin'), 'rb').read()
    assert p[:4] == b'WPP1', 'pools.bin magic'
    n = struct.unpack_from('<I', p, 4)[0]
    hdr = 8; body = 8 + 20 * n
    names, counts = [], []
    for t in range(n):
        h = p[hdr + 20 * t: hdr + 20 * t + 20]
        names.append(h[:8].split(b'\0')[0].decode())
        counts.append(struct.unpack_from('<6H', h, 8))
    out = []
    for t in range(n):
        words = {}
        for k in range(6):
            L = 4 + k; cnt = counts[t][k]
            words[L] = [p[body + i * L: body + (i + 1) * L].decode() for i in range(cnt)]
            body += cnt * L
        out.append((names[t], words))
    assert body == len(p), 'pools.bin has trailing bytes'
    return out

def dict_counts():
    p = open(os.path.join(REPO, 'data/dict.bin'), 'rb').read()
    assert p[:4] == b'WPD3', 'dict.bin magic'
    counts = struct.unpack_from('<18I', p, 4)
    rec = [4, 4, 4, 4, 5, 6, 7, 7, 8, 8, 9, 9, 10, 11, 11, 12, 13, 13]   # lengths 3..20 (dict.c recLen)
    off = 4 + 72; rare = []
    for i, L in enumerate(range(3, 21)):
        r = rec[i]; n = counts[i]; k = 0
        for j in range(n):
            if p[off + j * r + r - 1] & 1: k += 1
        rare.append(k); off += n * r
    assert off == len(p), 'dict.bin trailing bytes'
    return list(counts), rare

def variants_counts():
    p = open(os.path.join(REPO, 'data/variants.bin'), 'rb').read()
    assert p[:4] == b'WPV1'
    counts = struct.unpack_from('<18I', p, 4)
    rec = [4, 4, 4, 4, 5, 6, 7, 7, 8, 8, 9, 9, 10, 11, 11, 12, 13, 13]
    off = 4 + 72; us = uk = 0
    for i in range(18):
        r = rec[i]
        for j in range(counts[i]):
            if p[off + j * r + r - 1] & 1: uk += 1
            else: us += 1
        off += counts[i] * r
    return us, uk

def gfx_names():
    t = read(os.path.join(SRC, 'gfx.c'))
    def arr(name):
        m = re.search(name + r'\[[A-Z_]*\]\s*=\s*\{(.*?)\};', t, re.S)
        return re.findall(r'"([^"]*)"', m.group(1))
    return {k: arr(k) for k in ('OPT_NAMES', 'LIB_NAMES', 'SPELL_NAMES', 'THEME_NAMES', 'FRAME_NAMES', 'ACCENT_NAMES', 'FIRE_NAMES')}

