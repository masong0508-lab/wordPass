int fontLogoIndex(char ch)
{
    switch (ch) { case 'w': return 47; case 'o': return 48; case 'r': return 49; case 'd': return 50; }
    return fontIndex(ch);
}

int fontIndex(char ch)
{
    if (ch >= 'a' && ch <= 'z') return ch - 'a';
    if (ch >= 'A' && ch <= 'Z') return ch - 'A';
    if (ch >= '0' && ch <= '9') return 26 + (ch - '0');
    switch (ch) {
        case ':': return 37; case '!': return 38; case '?': return 39;
        case '.': return 40; case '-': return 41; case '+': return 42;
        case '_': return 43; case '/': return 44; case '@': return 45;
        case '\'': return 46;
        case '<': return 51; case '>': return 52;
        case '(': return 53; case ')': return 54; case '%': return 55;
        default:  return 36;
    }
}
